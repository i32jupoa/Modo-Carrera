export function mapEaPosition(pos: string): Position {















  if (pos === "GK") return "GK";















  const u = pos.toUpperCase();















  if (["CB", "LB", "RB", "LWB", "RWB", "SW", "LCB", "RCB"].includes(u)) return "DEF";















  if (["ST", "CF", "LW", "RW", "LF", "RF", "LS", "RS"].includes(u)) return "FWD";















  return "MID";















}































